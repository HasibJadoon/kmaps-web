-- Match terms against it. ʿAḍīma's headings wear a house prefix — لمحات عن دراسة X,
-- دراسة X, [X] — so strip that before deciding exact/prefix, or every entry reads as
-- 'contains' and the ranking stops meaning anything.
INSERT OR IGNORE INTO ar_ling_gram_term_toc
  (id, term_id, category_key, source_slug, source_rank, discipline,
   bab_id, bab_title_ar, page_start, match_kind, match_rank, external_url)
WITH ne AS (
  SELECT e.id AS eid, e.section, e.title_ar, e.url,
         replace(replace(replace(replace(replace(replace(replace(replace(replace(replace(replace(
           e.title_ar,'ً',''),'ٌ',''),'ٍ',''),'َ',''),'ُ',''),'ِ',''),'ّ',''),'ْ',''),'ٰ',''),'أ','ا'),'إ','ا') AS t
  FROM ar_ling_gram_external_toc e WHERE e.source_slug='adima_dirasat'
),
ne2 AS (
  SELECT eid, section, title_ar, url, t,
         trim(CASE
           WHEN t LIKE 'لمحات عن دراسة %' THEN substr(t, 17)
           WHEN t LIKE 'لمحات عن %'       THEN substr(t, 10)
           WHEN t LIKE 'دراسة %'          THEN substr(t, 7)
           WHEN t LIKE 'باب %'            THEN substr(t, 5)
           WHEN t LIKE '[%'               THEN replace(replace(t,'[',''),']','')
           ELSE t END) AS th
  FROM ne
),
nt AS (
  SELECT g.id, g.category_key,
         replace(replace(replace(replace(replace(replace(replace(replace(replace(replace(replace(
           g.name_ar,'ً',''),'ٌ',''),'ٍ',''),'َ',''),'ُ',''),'ِ',''),'ّ',''),'ْ',''),'ٰ',''),'أ','ا'),'إ','ا') AS t
  FROM ar_ling_gram_term g WHERE g.name_ar IS NOT NULL AND g.status='live'
),
nt2 AS (
  SELECT id, category_key, t, CASE WHEN t LIKE 'ال%' THEN substr(t,3) ELSE t END AS tb
  FROM nt WHERE length(t) > 2
),
m AS (
  SELECT nt2.id AS term_id, nt2.category_key, ne2.eid, ne2.section, ne2.title_ar, ne2.url,
         length(nt2.t) AS tlen,
         CASE
           WHEN ne2.th = nt2.t OR ne2.th = nt2.tb                 THEN 'exact'
           WHEN instr(ne2.th, nt2.t)=1 OR instr(ne2.th, nt2.tb)=1 THEN 'prefix'
           ELSE 'contains' END AS match_kind
  FROM nt2 JOIN ne2 ON instr(ne2.t, nt2.t)>0 OR instr(ne2.t, nt2.tb)>0
)
SELECT 'TOC:'||replace(term_id,'GT:','')||':'||eid, term_id, category_key,
       'adima_dirasat', 0, CASE section WHEN 'sarf' THEN 'SF' ELSE 'NH' END,
       eid, title_ar, NULL, match_kind,
       CASE match_kind WHEN 'exact' THEN 1 WHEN 'prefix' THEN 2 ELSE 3 END, url
FROM m
WHERE NOT (tlen <= 4 AND match_kind = 'contains');
