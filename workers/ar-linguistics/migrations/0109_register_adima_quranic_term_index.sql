-- 0109 — Register ʿAḍīma's Qurʾānic term index as a linkable table of contents.
--
-- محمد عبد الخالق عضيمة · دراسات لأسلوب القرآن الكريم is the one work in reach organised
-- the way this project needs: one entry per grammatical term, and inside each entry every
-- Qurʾānic instance of that term, enumerated with sūra:āya references. Only its table of
-- contents is stored here — 571 entries, each with a stable URL. The text stays at source.
--
--   المعجم الصرفي   389 entries   (jamharah f-495)
--   المعجم النحوي   182 entries   (jamharah f-496)
--
-- It reaches what no ingested book's TOC does:
--   الممنوع من الصرف            2 entries — an axis the 399-term registry has no term for
--   جمع المذكر/المؤنث السالم    — the plural_kind axis, likewise absent
--   تثنية الجمع واسم الجمع، اسم الجنس الجمعي — the collective axis, likewise absent
--   النسب                        2 entries, Qurʾān-exhaustive — and النسب had zero examples
--   المصدر على (فِعْلة) …       ~60 entries keyed BY WAZN — the bridge from the 465 patterns
--                                  in qr_lemma.wazn_ar to the classical label
--   باب نصر/ضرب/علم/فتح/كرم/حسب — the six Form I bābs, as Qurʾānic verb lists
--   المثال الواوي، الأجوف اليائي، الناقص، اللفيف المقرون/المفروق — the root_type axis, which
--                                  the ingested books' headings reached for only 2 of 15 terms
--
-- Rows land as state='auto'. Titles are the archive's own; nothing is a claim until confirmed.

DROP TABLE IF EXISTS ar_ling_gram_external_toc;

CREATE TABLE ar_ling_gram_external_toc (
  source_slug TEXT NOT NULL,
  section     TEXT NOT NULL,
  entry_no    INTEGER NOT NULL,
  title_ar    TEXT NOT NULL,
  url         TEXT GENERATED ALWAYS AS ('https://jamharah.net/archive/index.php/t-'||entry_no||'.html') VIRTUAL,
  id          TEXT GENERATED ALWAYS AS ('adima:'||section||':'||entry_no) VIRTUAL,
  PRIMARY KEY (source_slug, section, entry_no)
);

CREATE INDEX idx_ext_toc_title ON ar_ling_gram_external_toc (source_slug, title_ar);

ALTER TABLE ar_ling_gram_term_toc ADD COLUMN external_url TEXT;

