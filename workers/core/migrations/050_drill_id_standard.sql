-- 050 · The drill-id standard, from the km_core registries (owner, 2026-10-14).
-- A drill's global id names its DOMAIN and its SUB-DOMAIN, both read from Cybernetics:
--   DRL:<cyb_domain.code>:<cyb_discipline.code>:<the drill's own stable id>
--   e.g. DRL:QR:NH:fill:40:1:3 · DRL:AR:SF:sarf_mudari:كتب · DRL:WV:BL:rhetoric:recognise:12
-- The discipline is the drill's own (a grammar-term drill takes its term's, ar_ling_gram_term.discipline), else its
-- kind's row in cyb_drill_type, else its focus's (AR bucket · QR skill · WV card kind), else XX (unclassified — the
-- audit lists those, never a silent gap). Core stamps it when a drill is filed; the workers no longer make ids.

-- the domain's short code: the same prefix as the typed refs (QR: AR: WV: CM: AL:)
ALTER TABLE cyb_domain ADD COLUMN code TEXT;
UPDATE cyb_domain SET code = CASE slug WHEN 'quran' THEN 'QR' WHEN 'arabic' THEN 'AR' WHEN 'wv' THEN 'WV'
                                       WHEN 'doc' THEN 'CM' WHEN 'ling' THEN 'AL' END;
CREATE UNIQUE INDEX IF NOT EXISTS idx_cyb_domain_code ON cyb_domain (code);

