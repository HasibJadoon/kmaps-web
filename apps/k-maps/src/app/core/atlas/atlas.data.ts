export const RESEARCH_THEME_EDGES: AtlasEdge[] = [
  ...RESEARCH_THEME_SEEDS.flatMap((theme) => {
    const conceptIds = theme.concepts.map((concept) => researchNodeId(theme.cluster_id, concept.slug, 'concept'));

    return theme.concepts.flatMap((concept, index) => {
      const conceptId = researchNodeId(theme.cluster_id, concept.slug, 'concept');
      const claimId = researchNodeId(theme.cluster_id, concept.slug, 'claim');
      const evidenceId = researchNodeId(theme.cluster_id, concept.slug, 'evidence');
      const chainTarget = conceptIds[(index + 1) % conceptIds.length];
      const bridgeEdges = (concept.bridges ?? []).map((bridge, bridgeIndex) => ({
        id: `rx_bridge_${theme.cluster_id}_${concept.slug}_${bridgeIndex + 1}`,
        source:
          bridge.from === 'claim'
            ? claimId
            : bridge.from === 'evidence'
              ? evidenceId
              : conceptId,
        target: bridge.target,
        type: bridge.type ?? 'related_to',
        strength: bridge.strength ?? 0.6,
      }));

      return [
        {
          id: `rx_edge_${theme.cluster_id}_${concept.slug}_claim`,
          source: conceptId,
          target: claimId,
          type: 'articulates',
          strength: 0.84,
        },
        {
          id: `rx_edge_${theme.cluster_id}_${concept.slug}_evidence`,
          source: claimId,
          target: evidenceId,
          type: concept.evidence_link_type ?? 'grounds',
          strength: 0.76,
        },
        {
          id: `rx_edge_${theme.cluster_id}_${concept.slug}_chain`,
          source: conceptId,
          target: chainTarget,
          type: 'related_to',
          strength: 0.46,
        },
        ...bridgeEdges,
      ];
    });
  }),
];

